import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createHash} from 'node:crypto';
import {verifyAndCapture} from '../tools/stage98_drand_evidence.mjs';
const b=JSON.parse(fs.readFileSync(new URL('./fixtures/stage94r_public_beacon.json',import.meta.url),'utf8'));
const info={public_key:'868f005eb8e6e4ca0a47c8a77ceaa5309a47978a7c71bc5cce96366b5d7a569937c529eeda66c7293784a9402801af31',schemeID:'pedersen-bls-chained',hash:'8990e7a9aaed2ffed73dbd7092123d6f289930540d7651336225dc172e51b2ce',period:30,genesis_time:1595431050};
const when=(1595431050+(b.round-1)*30)*1000;
let network=0;globalThis.fetch=()=>{network++;throw Error('OFFLINE_ONLY')};
const make=(beacon=b,chain=info,disable=false)=>({options:{disableBeaconVerification:disable},get:async()=>beacon,chain:()=>({info:async()=>chain})});
const args=(over={})=>({round:b.round,randomness:b.randomness,signature:b.signature,maxAge:120,client:make(),now:()=>when+29000,...over});
const fail=(over)=>assert.rejects(verifyAndCapture(args(over)));
test('real historical BLS signature and exact capture',async()=>{const r=await verifyAndCapture(args());assert.deepEqual(r.beacon,b);assert.equal(r.age_seconds,29);assert.equal(r.status,'PASS');assert.equal(network,0)});
test('wrong round',()=>fail({round:b.round+1}));
test('randomness tamper',()=>fail({randomness:'0'.repeat(64)}));
test('signature tamper even with recomputed randomness',()=>{const sig=b.signature.slice(0,-2)+(b.signature.endsWith('00')?'01':'00'),randomness=createHash('sha256').update(Buffer.from(sig,'hex')).digest('hex');return fail({signature:sig,randomness,client:make({...b,signature:sig,randomness})})});
test('previous signature tamper',()=>fail({client:make({...b,previous_signature:'0'.repeat(192)})}));
test('missing previous signature',()=>{const {previous_signature,...c}=b;return fail({client:make(c)})});
test('wrong key',()=>fail({client:make(b,{...info,public_key:'0'.repeat(96)})}));
test('wrong chain',()=>fail({client:make(b,{...info,hash:'0'.repeat(64)})}));
test('wrong scheme',()=>fail({client:make(b,{...info,schemeID:'other'})}));
test('disabled verification',()=>fail({client:make(b,info,true)}));
test('expiry',()=>fail({now:()=>when+121000}));
test('future',()=>fail({now:()=>when-1000}));
test('exact age limit',async()=>assert.equal((await verifyAndCapture(args({now:()=>when+120000}))).age_seconds,120));
test('no network used',()=>assert.equal(network,0));
